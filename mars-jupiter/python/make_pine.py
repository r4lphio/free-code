"""Write the TradingView indicator (mars-jupiter-aspects.pine) from the aspect dates in data/aspects.csv.

The dates are embedded in the script, so TradingView needs no outside data. Run aspects.py first to make the CSV.
Usage: python make_pine.py data/aspects.csv ../mars-jupiter-aspects.pine
"""

import sys
from pathlib import Path

import pandas as pd

CODES = {"conjunction": 0, "sextile": 1, "square": 2, "trine": 3, "opposition": 4}

TEMPLATE = r'''// Mars-Jupiter Aspects, free from r4lph.io (https://r4lph.io/free-trading-systems/mars-jupiter)
// An experiment in what AI agents can build and verify, not trading advice.
//
// What it does: marks every exact Mars-Jupiter aspect from {first} to {last} on any chart, shows the next ones
// ahead of price, and (optional) tests the simple trade from the video on the chart's own symbol.
//
// Where the dates come from: NASA JPL's public DE440s ephemeris, computed with the open-source Skyfield library
// (aspects.py in the Python folder) and checked against Swiss Ephemeris. Positions are geocentric, tropical
// (ecliptic longitude of date). Aspects: conjunction 0, sextile 60, square 90, trine 120, opposition 180 degrees.
// Every exact crossing is listed, including the second and third hits when Mars turns retrograde.
//
// The test trade (as in the video): on the first bar on or after an aspect's date (UTC), enter at the open.
// Long after a conjunction, sextile or trine; short after a square or opposition. Exit at the open N bars
// later. One trade at a time. The cost comes off each trade, once on entry and once on exit.
//
// Generated by make_pine.py from aspects.csv. Edit those, not this file.
//@version=6
indicator("Mars-Jupiter Aspects", overlay = true, max_labels_count = 500, max_lines_count = 100)

// ---- Inputs ----
showConj  = input.bool(true, "Conjunction (0°)", group = "Aspects")
showSext  = input.bool(true, "Sextile (60°)", group = "Aspects")
showSq    = input.bool(true, "Square (90°)", group = "Aspects")
showTrine = input.bool(true, "Trine (120°)", group = "Aspects")
showOpp   = input.bool(true, "Opposition (180°)", group = "Aspects")
showLabels = input.bool(true, "Show labels", group = "Display")
showBg     = input.bool(true, "Shade the aspect bar", group = "Display")
nextCount  = input.int(4, "Upcoming aspects to draw", minval = 0, maxval = 20, group = "Display")
easyColor  = input.color(color.new(#6fb3a8, 0), "Easy aspects (sextile, trine)", group = "Display")
hardColor  = input.color(color.new(#d9644a, 0), "Hard aspects (square, opposition)", group = "Display")
conjColor  = input.color(color.new(#d4924f, 0), "Conjunction", group = "Display")
doTest   = input.bool(true, "Test the trade from the video", group = "Test trade")
holdBars = input.int(10, "Hold (bars)", minval = 1, group = "Test trade")
costBps  = input.float(5.0, "Cost each way (basis points)", minval = 0, group = "Test trade")

// ---- Aspect dates: exact time in UTC milliseconds, and the aspect (0 conj, 1 sextile, 2 square, 3 trine, 4 opp) ----
{arrays}

aspectName(int c) =>
    c == 0 ? "Conjunction" : c == 1 ? "Sextile" : c == 2 ? "Square" : c == 3 ? "Trine" : "Opposition"

aspectColor(int c) =>
    c == 0 ? conjColor : (c == 1 or c == 3) ? easyColor : hardColor

shown(int c) =>
    c == 0 ? showConj : c == 1 ? showSext : c == 2 ? showSq : c == 3 ? showTrine : showOpp

// Midnight UTC of the calendar day that holds UTC time t.
utcDay(int t) =>
    timestamp("UTC", year(t, "UTC"), month(t, "UTC"), dayofmonth(t, "UTC"), 0, 0, 0)

// This bar's calendar date (in the exchange's time zone, as a chart shows it), as midnight UTC.
barDay = timestamp("UTC", year(time, syminfo.timezone), month(time, syminfo.timezone), dayofmonth(time, syminfo.timezone), 0, 0, 0)

// ---- Walk the dates: each aspect lands on the first bar on or after its UTC date ----
var int ptr = 0
if barstate.isfirst
    // Aspects before the chart's first bar are skipped, as in the Python test.
    while ptr < array.size(T) and utcDay(array.get(T, ptr)) < barDay
        ptr += 1

int hitCode = -1      // the first aspect on this bar (it decides the test trade's side)
string hitText = ""
color hitColor = na
while ptr < array.size(T) and utcDay(array.get(T, ptr)) <= barDay
    c = array.get(A, ptr)
    if hitCode == -1
        hitCode := c
    if shown(c)
        hitText := hitText + (hitText == "" ? "" : "\n") + aspectName(c) + " " + str.format_time(array.get(T, ptr), "yyyy-MM-dd HH:mm", "UTC") + " UTC"
        hitColor := na(hitColor) ? aspectColor(c) : hitColor
    ptr += 1

bgcolor(showBg and hitText != "" ? color.new(hitColor, 80) : na)
if showLabels and hitText != ""
    label.new(bar_index, high, hitText, style = label.style_label_down, color = color.new(hitColor, 15), textcolor = color.white, size = size.small)

// ---- Upcoming aspects, drawn ahead of price ----
if barstate.islast and nextCount > 0
    int drawn = 0
    for i = 0 to array.size(T) - 1
        t = array.get(T, i)
        c = array.get(A, i)
        if utcDay(t) > barDay and shown(c) and drawn < nextCount
            line.new(t, low, t, high, xloc = xloc.bar_time, extend = extend.both, color = aspectColor(c), style = line.style_dashed)
            label.new(t, high, aspectName(c) + "\n" + str.format_time(t, "yyyy-MM-dd", "UTC"), xloc = xloc.bar_time, style = label.style_label_down, color = color.new(aspectColor(c), 15), textcolor = color.white, size = size.small)
            drawn += 1

// ---- The test trade ----
var bool inTrade = false
var int entryBar = 0
var float entryPrice = na
var int side = 0
var int trades = 0
var int wins = 0
var float sumRet = 0.0
cost = costBps / 10000.0
if doTest
    // Exit first, so a new aspect can enter on the same bar, as in the Python test.
    if inTrade and bar_index - entryBar >= holdBars
        ratio = open / entryPrice
        r = math.max(side > 0 ? ratio - 1 : 1 - ratio, -1.0) - 2 * cost
        trades += 1
        wins += r > 0 ? 1 : 0
        sumRet += r
        inTrade := false
    if not inTrade and hitCode >= 0
        inTrade := true
        entryBar := bar_index
        entryPrice := open
        side := (hitCode == 0 or hitCode == 1 or hitCode == 3) ? 1 : -1

var table box = table.new(position.top_right, 2, 6, bgcolor = color.new(#0f0f1a, 10), border_color = color.new(#26243a, 0), border_width = 1)
if barstate.islast
    int nxt = -1
    for i = 0 to array.size(T) - 1
        if utcDay(array.get(T, i)) > barDay and shown(array.get(A, i))
            nxt := i
            break
    table.cell(box, 0, 0, "Mars-Jupiter", text_color = color.white)
    table.cell(box, 1, 0, "public ephemeris", text_color = color.gray)
    table.cell(box, 0, 1, "Next aspect", text_color = color.gray)
    table.cell(box, 1, 1, nxt >= 0 ? aspectName(array.get(A, nxt)) + " " + str.format_time(array.get(T, nxt), "yyyy-MM-dd", "UTC") : "after {last}", text_color = color.white)
    if doTest
        table.cell(box, 0, 2, "Test trades (closed)", text_color = color.gray)
        table.cell(box, 1, 2, str.tostring(trades), text_color = color.white)
        table.cell(box, 0, 3, "Average trade, after cost", text_color = color.gray)
        table.cell(box, 1, 3, trades > 0 ? str.tostring(100 * sumRet / trades, "#.##") + "%" : "-", text_color = color.white)
        table.cell(box, 0, 4, "Winning trades", text_color = color.gray)
        table.cell(box, 1, 4, trades > 0 ? str.tostring(100.0 * wins / trades, "#.#") + "%" : "-", text_color = color.white)
        table.cell(box, 0, 5, "Not trading advice", text_color = color.gray)
        table.cell(box, 1, 5, "r4lph.io", text_color = color.gray)
'''


def pine_array(name: str, values: list[int], kind: str) -> str:
    """A Pine array built from chunks of 40 literals (keeps each line short)."""
    chunks = [values[i:i + 40] for i in range(0, len(values), 40)]
    lines = [f"var array<{kind}> {name} = array.from({', '.join(map(str, chunks[0]))})"]
    lines += [f"if barstate.isfirst\n    array.concat({name}, array.from({', '.join(map(str, c))}))" for c in chunks[1:]]
    return "\n".join(lines)


def main() -> None:
    src, out = Path(sys.argv[1]), Path(sys.argv[2])
    ev = pd.read_csv(src, parse_dates=["utc"]).sort_values("utc")
    ms = [int(t.value // 1_000_000) for t in ev.utc]
    codes = [CODES[a] for a in ev.aspect]
    arrays = pine_array("T", ms, "int") + "\n" + pine_array("A", codes, "int")
    text = TEMPLATE.replace("{arrays}", arrays)
    text = text.replace("{first}", ev.utc.iloc[0].strftime("%Y")).replace("{last}", ev.utc.iloc[-1].strftime("%Y"))
    out.write_text(text)
    print(f"{len(ms)} aspects, {ev.utc.iloc[0]:%Y-%m-%d} to {ev.utc.iloc[-1]:%Y-%m-%d} -> {out}")


if __name__ == "__main__":
    main()
